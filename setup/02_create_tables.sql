-- =============================================================================
-- 5. ORDERS (order headers) — Standard tier: 5,000,000 rows
--    RANGE PARTITIONED BY ORDER_DATE, monthly, via INTERVAL partitioning.
--
-- INTERVAL partitioning (11g+) is used instead of hand-listing ~24 monthly
-- partitions: one explicit starting partition defines the transition
-- point, and Oracle creates each subsequent monthly partition
-- automatically the first time a row needs it. 04_generate_data.sql
-- generates ORDER_DATE values across roughly a 2-year window starting at
-- the boundary below, which yields the ~24 monthly partitions the course
-- design calls for.
--
-- ENVIRONMENT DEPENDENT / instructor note: the date window below
-- (2024-01-01 onward) is a fixed training window, not tied to "today."
-- Adjust the starting boundary if you want the lab data to read as
-- current relative to when you are actually running the course — just
-- keep ORDERS and SALES (step 9) using the SAME starting boundary, since
-- Day 27's partition-wise join demo depends on both tables' monthly
-- partitions being aligned.
--
-- PRIMARY KEY INDEX: ORDER_ID is a surrogate key unrelated to ORDER_DATE,
-- so its PK constraint creates a single GLOBAL (non-partitioned) unique
-- index by default — this is standard, unavoidable Oracle behavior for a
-- unique/PK constraint on a partitioned table whose key isn't a superset
-- of the partition key. That tradeoff (a global index needs its own
-- maintenance on partition operations such as DROP/EXCHANGE PARTITION)
-- is exactly what Day 27 discusses.
-- =============================================================================
PROMPT Creating ORDERS (interval-partitioned by ORDER_DATE) ...

CREATE TABLE orders (
  order_id                NUMBER(12)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
  customer_id             NUMBER(10)     NOT NULL,
  order_date              DATE           NOT NULL,   -- partition key
  order_status            VARCHAR2(20)   NOT NULL,
  order_channel           VARCHAR2(20)   DEFAULT 'WEB' NOT NULL,
  ship_date               DATE,
  required_date           DATE,
  order_total             NUMBER(12,2)   NOT NULL,
  tax_amount               NUMBER(10,2)   DEFAULT 0 NOT NULL,
  shipping_amount          NUMBER(10,2)   DEFAULT 0 NOT NULL,
  discount_amount          NUMBER(10,2)   DEFAULT 0 NOT NULL,
  currency_code            CHAR(3)        DEFAULT 'USD' NOT NULL,
  payment_method           VARCHAR2(20),
  shipping_address_line1   VARCHAR2(100),
  shipping_city            VARCHAR2(60),
  shipping_state           VARCHAR2(60),
  shipping_postal_code     VARCHAR2(20),
  sales_rep_id              NUMBER(8),
  notes                     VARCHAR2(4000),
  created_at                TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at                TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_orders            PRIMARY KEY (order_id),
  CONSTRAINT fk_orders_customer   FOREIGN KEY (customer_id) REFERENCES customers(customer_id),
  CONSTRAINT fk_orders_employee   FOREIGN KEY (sales_rep_id) REFERENCES employees(employee_id),
  CONSTRAINT ck_orders_status     CHECK (order_status IN
                                     ('PENDING','PROCESSING','SHIPPED','DELIVERED','CANCELLED','RETURNED')),
  CONSTRAINT ck_orders_channel    CHECK (order_channel IN ('WEB','MOBILE','STORE','PHONE'))
)
PARTITION BY RANGE (order_date)
INTERVAL (NUMTOYMINTERVAL(1,'MONTH'))
(
  PARTITION p_orders_start VALUES LESS THAN (DATE '2024-01-01')
);

