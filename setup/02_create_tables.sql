-- =============================================================================
-- PERF_LAB Setup — Script 02 of 7
-- 02_create_tables.sql
--
-- Purpose: create all 10 PERF_LAB tables — an order-processing/payments
-- application schema — with realistic columns, primary keys, foreign
-- keys, and the two partitioned tables (ORDERS, SALES) the course design
-- calls for.
--
-- Run connected AS perf_lab (created by 01_create_user.sql):
--   sqlplus perf_lab/<password>@//localhost:1521/PERFPDB @02_create_tables.sql
--
-- This script assumes a clean, empty PERF_LAB schema (freshly created by
-- 01_create_user.sql). It does not attempt to be idempotent/re-runnable
-- against a schema that already has these objects — to rebuild from
-- scratch, drop and recreate the PERF_LAB user first.
--
-- INDEX PHILOSOPHY (read before 03_create_indexes.sql):
-- Every PRIMARY KEY / UNIQUE constraint below creates its own supporting
-- unique index automatically as part of this script — that is unavoidable
-- Oracle behavior, not a tuning decision. Beyond that, this script and
-- 03_create_indexes.sql deliberately do NOT add indexes on foreign-key
-- columns (e.g. ORDER_ITEMS.PRODUCT_ID, ORDERS.CUSTOMER_ID). That gap is
-- intentional: several days in this course (Day 2's investigation demo,
-- Day 23's indexing-strategy lab, among others) exist specifically to
-- teach students to diagnose and fix the consequences of an unindexed
-- foreign key. See 03_create_indexes.sql for the full rationale.
--
-- SURROGATE KEYS: every table's primary key is an IDENTITY column
-- (GENERATED BY DEFAULT ON NULL AS IDENTITY). "BY DEFAULT ON NULL" (as
-- opposed to "ALWAYS") is deliberate: it lets 04_generate_data.sql supply
-- explicit, densely-packed key values for fast bulk loading, while still
-- allowing ordinary single-row INSERTs in later days' demos to omit the
-- key and get one generated automatically. 04_generate_data.sql reseeds
-- each identity generator's next value after the bulk load completes
-- (ALTER TABLE ... MODIFY ... GENERATED ... START WITH LIMIT VALUE) so
-- those later single-row inserts don't collide with bulk-loaded IDs.
-- =============================================================================

