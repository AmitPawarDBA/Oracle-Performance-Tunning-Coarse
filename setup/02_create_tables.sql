-- =============================================================================
-- 8. TRANSACTIONS (general-ledger-style transaction log) — Standard tier: 10,000,000 rows
--
-- Deliberately NOT foreign-keyed to ORDERS/PAYMENTS: REFERENCE_TYPE +
-- REFERENCE_ID is a loose, polymorphic pointer (a common, real-world
-- general-ledger pattern — one GL log feeding from many different source
-- systems/tables). Enforcing a single FK here would misrepresent how
-- these tables actually relate in practice, so it is intentionally
-- omitted rather than an oversight. High-volume I/O and TEMP-spill demo
-- source for Days 29-30.
-- =============================================================================
PROMPT Creating TRANSACTIONS ...

CREATE TABLE transactions (
  transaction_id     NUMBER(14)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
  transaction_date   DATE          NOT NULL,
  transaction_type   VARCHAR2(20)  NOT NULL,
  account_id         NUMBER(10)    NOT NULL,
  reference_type     VARCHAR2(20),          -- 'ORDER' / 'PAYMENT' / 'MANUAL' / 'SYSTEM' — no enforced FK, see above
  reference_id       NUMBER(14),
  amount             NUMBER(14,2)  NOT NULL,
  currency_code      CHAR(3)       DEFAULT 'USD' NOT NULL,
  gl_account_code    VARCHAR2(20),
  description        VARCHAR2(200),
  posted_by          VARCHAR2(30)  DEFAULT USER NOT NULL,
  created_at         TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_transactions       PRIMARY KEY (transaction_id),
  CONSTRAINT ck_transactions_type  CHECK (transaction_type IN ('DEBIT','CREDIT','ADJUSTMENT','FEE','REFUND'))
);

-- =============================================================================
-- 9. SALES (aggregated sales facts) — Standard tier: 10,000,000 rows
--    RANGE PARTITIONED BY SALE_DATE, monthly, via INTERVAL partitioning —
--    the SAME starting boundary as ORDERS (step 5), so Day 27 can
--    demonstrate a partition-wise join between the two.
--
-- FK to PRODUCTS and CUSTOMERS (typical star-schema fact-to-dimension
-- pattern). ORDER_ID is a loose reference back to the originating order,
-- deliberately NOT foreign-keyed — SALES is an aggregated/derived fact
-- table, and real data-warehouse fact tables commonly do not enforce FKs
-- back to the transactional source system that fed them.
-- =============================================================================
PROMPT Creating SALES (interval-partitioned by SALE_DATE) ...

CREATE TABLE sales (
  sale_id         NUMBER(14)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
  sale_date       DATE          NOT NULL,   -- partition key; aligned with ORDERS.ORDER_DATE boundaries
  product_id      NUMBER(10)    NOT NULL,
  customer_id     NUMBER(10),
  region          VARCHAR2(20),
  quantity_sold   NUMBER(10)    NOT NULL,
  unit_price      NUMBER(10,2)  NOT NULL,
  total_amount    NUMBER(14,2)  NOT NULL,
  order_id        NUMBER(12),                -- loose reference to ORDERS; intentionally not FK-enforced, see above
  created_at      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_sales           PRIMARY KEY (sale_id),
  CONSTRAINT fk_sales_product   FOREIGN KEY (product_id) REFERENCES products(product_id),
  CONSTRAINT fk_sales_customer  FOREIGN KEY (customer_id) REFERENCES customers(customer_id)
)
PARTITION BY RANGE (sale_date)
INTERVAL (NUMTOYMINTERVAL(1,'MONTH'))
(
  PARTITION p_sales_start VALUES LESS THAN (DATE '2024-01-01')
);

-- =============================================================================
-- 10. LOG_EVENTS (application/event log) — Standard tier: 20,000,000 rows
--
-- Insert-heavy design, deliberately: LOG_ID is a plain monotonically
-- increasing surrogate key, which is a well-known real-world anti-pattern
-- under heavy concurrent insert load (every session's next insert
-- competes for the same "right-hand" leaf block of the primary-key
-- index — index/buffer hot-block contention). This is left exactly as a
-- typical, unremarkable-looking table would be built, on purpose: it is
-- the deliberate setup for Day 31's concurrency/hot-block demo (and, more
-- generally, Day 17's redo/log-sync demo under insert load). Do not
-- "improve" this design (e.g. with a reverse-key index) here — Day 31
-- teaches that fix as part of diagnosing the problem it causes.
--
-- No foreign keys: log/event tables in real systems are routinely
-- decoupled from the OLTP schema on purpose (so logging never blocks on,
-- or is blocked by, application-table locking, and so the log survives
-- even if the referenced business row is later purged/archived).
--
-- EVENT_DETAIL is a VARCHAR2, not a CLOB: a 20-million-row CLOB column
-- would meaningfully complicate bulk generation (LOB space management,
-- much larger storage/redo footprint) without adding teaching value this
-- course's days actually use — kept as VARCHAR2 deliberately.
-- =============================================================================
PROMPT Creating LOG_EVENTS ...

CREATE TABLE log_events (
  log_id           NUMBER(14)     GENERATED BY DEFAULT ON NULL AS IDENTITY,  -- deliberate monotonic PK; see note above
  log_timestamp    TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  event_type       VARCHAR2(30)   NOT NULL,
  event_source     VARCHAR2(50),
  severity         VARCHAR2(10)   DEFAULT 'INFO' NOT NULL,
  session_id       VARCHAR2(50),
  user_id          NUMBER(10),         -- loosely related to CUSTOMERS/EMPLOYEES; intentionally not FK-enforced
  host_name        VARCHAR2(60),
  message          VARCHAR2(500),
  event_detail     VARCHAR2(4000),
  created_at       TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_log_events       PRIMARY KEY (log_id),
  CONSTRAINT ck_log_events_sev   CHECK (severity IN ('DEBUG','INFO','WARN','ERROR','FATAL'))
);

