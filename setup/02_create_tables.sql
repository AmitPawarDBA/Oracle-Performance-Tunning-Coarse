-- =============================================================================
-- 2. EMPLOYEES (internal staff) — Standard tier: 10,000 rows
--
-- Self-referencing FK (manager_id -> employees.employee_id) is declared
-- inline; Oracle allows this because the constraint is validated against
-- row data, not against the table's DDL-time existence.
-- =============================================================================
PROMPT Creating EMPLOYEES ...

CREATE TABLE employees (
  employee_id      NUMBER(8)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
  employee_number  VARCHAR2(20)  NOT NULL,
  first_name       VARCHAR2(50)  NOT NULL,
  last_name        VARCHAR2(50)  NOT NULL,
  email            VARCHAR2(100),
  phone            VARCHAR2(20),
  hire_date        DATE          NOT NULL,
  job_title        VARCHAR2(60),
  department_id    NUMBER(6),
  manager_id       NUMBER(8),
  salary           NUMBER(10,2),
  employee_status  VARCHAR2(15)  DEFAULT 'ACTIVE' NOT NULL,
  created_at       TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
